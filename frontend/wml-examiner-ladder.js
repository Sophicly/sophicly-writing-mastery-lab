/**
 * wml-examiner-ladder.js — the examiner-ladder ENGINE (v7.20.546, CW trials slice 2a)
 *
 * PURE LOGIC ONLY. No DOM, no chat, no document writes — the walk that drives this lives in
 * wml-assessment.js. Everything here is a function of (mark scheme, the student's answers), so
 * it is testable in node and its arithmetic can be gated (bin/examiner-ladder-harness.js).
 *
 * ⭐ WHY A LADDER AND NOT A PICKER (Neil, 2026-08-21, from his own 1:1 teaching; #407 supersedes
 * #221's step 1). The real examiner reads the BOTTOM level first and checks every criterion is
 * met, then climbs. On the first level not fully met, they place the student at the top, middle
 * or bottom of it. A top-down pick invites a student to flatter themselves in one tap; climbing
 * from the bottom forces them to actually read Level 1 and Level 2 — which is where a weak piece
 * genuinely sits, and where the honest evidence is.
 *
 * ⭐ THE GRANULARITY IS NEIL'S, from #221, and it is NOT re-derived here:
 *   level (from the climb) → upper/lower BAND where the board prints one → placement in that band.
 * AQA's AO5 genuinely splits (Upper L4 22–24 vs Lower L4 19–21, distinct descriptor sets); its
 * AO6 does not. So the band step is served only where the source data has bands — never invented
 * for a scheme that lacks them.
 *
 * ⭐ THE MARK IS ARITHMETIC, NEVER A NUMBER ANYONE TYPES — not the student's, not the model's.
 * It is derived from the range the student's own answers landed in:
 *   bottom → the range's lowest mark · top → its highest · middle → the mark between.
 * A 3-mark band (22–24) maps exactly. Where a range does not divide by three (AO6's 4-mark
 * levels, 13–16), the middle takes the LOWER of the two central marks — i.e. `floor`. That is
 * not a coin toss: Sophicly marks deliberately STRICTER than the examiner
 * (`feedback_marking_stricter_than_examiners_ericsson`, grade 9 = 85%), so where rounding is
 * ambiguous it rounds DOWN. Stated here because it is the one place a reader would otherwise
 * wonder whether a number was invented.
 *
 * ⛔ THE DESCRIPTORS ARE NEVER AUTHORED HERE. They arrive from window.WML_MARK_SCHEMES, which is
 * generated by bin/build-markscheme-dataset.js from the board's own document and gated against it
 * by bin/markscheme-gate.js. Two copies of a mark scheme is the drift class this repo keeps
 * getting bitten by.
 */
(function () {
    'use strict';

    // ── the rungs ───────────────────────────────────────────────────────────────────────────
    /**
     * A scheme's levels are stored top-down, as the board prints them. The climb is bottom-up,
     * so this returns them lowest-first — the ONE place the order is reversed. Nothing else in
     * the engine or the walk may re-sort them, or the climb silently runs the examiner's
     * procedure backwards.
     */
    function rungs(scheme) {
        if (!scheme || !Array.isArray(scheme.levels)) return [];
        return scheme.levels.slice().sort(function (a, b) { return a.min - b.min; });
    }

    /** Every descriptor of a level, flattened, each tagged with the strand it came from. */
    function descriptorsOf(level) {
        const out = [];
        if (!level || !Array.isArray(level.bands)) return out;
        level.bands.forEach(function (band) {
            (band.strands || []).forEach(function (strand) {
                (strand.descriptors || []).forEach(function (text) {
                    out.push({ text: text, strand: strand.name || null, band: band.name || null });
                });
            });
        });
        return out;
    }

    /**
     * The descriptors a student is asked to prove at a rung. Where a level has Upper/Lower bands
     * the two carry DIFFERENT wordings of the same criteria, and the climb is a question about
     * the LEVEL, not the band — so the rung is judged on the LOWER band's descriptors (the
     * threshold for being in the level at all). The upper wording is what the band step then
     * asks about. Levels with a single band use that band.
     */
    function climbDescriptors(level) {
        if (!level || !Array.isArray(level.bands) || !level.bands.length) return [];
        const lowest = level.bands.slice().sort(function (a, b) { return a.min - b.min; })[0];
        return descriptorsOf({ bands: [lowest] });
    }

    /** Does this level print its own Upper/Lower split? (AO5 yes, AO6 no.) */
    function hasBands(level) {
        return !!(level && Array.isArray(level.bands) && level.bands.length > 1);
    }

    function bandsOf(level) {
        if (!hasBands(level)) return [];
        return level.bands.slice().sort(function (a, b) { return b.min - a.min; }); // upper first
    }

    // ── the arithmetic ──────────────────────────────────────────────────────────────────────
    const PLACEMENTS = ['bottom', 'middle', 'top'];

    /**
     * The mark, from the range the student's answers landed in.
     * @param {{min:number,max:number}} range  a band where the board prints one, else the level
     * @param {'bottom'|'middle'|'top'} placement
     */
    function markFor(range, placement) {
        if (!range || typeof range.min !== 'number' || typeof range.max !== 'number') return null;
        if (PLACEMENTS.indexOf(placement) < 0) return null;
        if (placement === 'bottom') return range.min;
        if (placement === 'top') return range.max;
        return Math.floor((range.min + range.max) / 2);   // stricter-on-ambiguity, see header
    }

    /**
     * Resolve a completed climb to a mark.
     * @param {object} scheme   one entry of WML_MARK_SCHEMES
     * @param {object} verdict  { levelNumber, bandName?, placement }
     * @returns {{mark:number, outOf:number, level:number, band:string|null, placement:string,
     *            range:{min:number,max:number}}|null}
     */
    function resolve(scheme, verdict) {
        if (!scheme || !verdict) return null;
        const level = rungs(scheme).filter(function (l) { return l.level === verdict.levelNumber; })[0];
        if (!level) return null;
        let range = { min: level.min, max: level.max };
        let bandName = null;
        if (hasBands(level) && verdict.bandName) {
            const band = level.bands.filter(function (b) { return b.name === verdict.bandName; })[0];
            if (!band) return null;                       // a band we do not print is not a band
            range = { min: band.min, max: band.max };
            bandName = band.name;
        }
        const mark = markFor(range, verdict.placement);
        if (mark === null) return null;
        return {
            mark: mark, outOf: scheme.maxMarks, level: level.level,
            band: bandName, placement: verdict.placement, range: range,
        };
    }

    /**
     * A student who meets EVERY descriptor of the TOP level has climbed out of the ladder — the
     * procedure has no "next level" to move to, so they are placed in the top level rather than
     * left with no verdict (§4d: a walk may never end with nothing on the screen).
     */
    function topOut(scheme) {
        const r = rungs(scheme);
        return r.length ? r[r.length - 1] : null;
    }

    /**
     * THE CLIMB, as a pure state machine. The walk asks the questions; this decides what is
     * asked next and never asks twice.
     *
     * state = { levelIndex, metAll: {levelNumber:boolean}, partial: {descriptorIndexes:[]},
     *           bandName, placement, reason }
     * @returns {{step:string, level?:object, ...}}  the next thing to ask
     */
    function next(scheme, state) {
        const r = rungs(scheme);
        if (!r.length) return { step: 'error', why: 'this scheme has no levels' };
        const s = state || {};
        const i = typeof s.levelIndex === 'number' ? s.levelIndex : 0;

        // Climbed past the top: every level fully met.
        if (i >= r.length) {
            const top = topOut(scheme);
            if (!s.bandName && hasBands(top)) return { step: 'band', level: top, bands: bandsOf(top) };
            if (!s.placement) return { step: 'placement', level: top, range: bandRange(top, s.bandName) };
            if (!s.reason) return { step: 'reason', level: top };
            return { step: 'done', level: top };
        }

        const level = r[i];
        if (s.metAll && Object.prototype.hasOwnProperty.call(s.metAll, level.level)) {
            if (s.metAll[level.level] === true) {
                // met every criterion — climb, and never re-ask this rung
                return next(scheme, Object.assign({}, s, { levelIndex: i + 1 }));
            }
            // stopped here: which did they meet, then band, then placement, then why
            if (!s.partial) return { step: 'which', level: level, descriptors: climbDescriptors(level) };
            if (!s.bandName && hasBands(level)) return { step: 'band', level: level, bands: bandsOf(level) };
            if (!s.placement) return { step: 'placement', level: level, range: bandRange(level, s.bandName) };
            if (!s.reason) return { step: 'reason', level: level };
            return { step: 'done', level: level };
        }
        return { step: 'climb', level: level, descriptors: climbDescriptors(level) };
    }

    function bandRange(level, bandName) {
        if (bandName && hasBands(level)) {
            const b = level.bands.filter(function (x) { return x.name === bandName; })[0];
            if (b) return { min: b.min, max: b.max };
        }
        return { min: level.min, max: level.max };
    }

    /**
     * The rung a resume must land on — the exact descriptor set the student was reading, never
     * the top of the AO (§4c.8b). Returns the same shape as next(), so a resume and a fresh turn
     * are literally the same code path.
     */
    function resumeAt(scheme, state) { return next(scheme, state); }

    const API = {
        rungs: rungs,
        descriptorsOf: descriptorsOf,
        climbDescriptors: climbDescriptors,
        hasBands: hasBands,
        bandsOf: bandsOf,
        bandRange: bandRange,
        markFor: markFor,
        resolve: resolve,
        topOut: topOut,
        next: next,
        resumeAt: resumeAt,
        PLACEMENTS: PLACEMENTS,
    };
    if (typeof window !== 'undefined') { window.WML_EXAMINER_LADDER = API; }
    if (typeof module !== 'undefined' && module.exports) { module.exports = API; }
})();
